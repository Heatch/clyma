#!/usr/bin/env node
// scripts/export-d1-sql.mjs — dump the local SQLite database as a single
// SQL file for Cloudflare D1 (schema + data, FK-safe order).
//
//   node --experimental-sqlite scripts/export-d1-sql.mjs [--out PATH]
//
// Then apply it with wrangler:
//   npx wrangler d1 execute clyma --remote --file data/d1-import.sql --yes
//
// The dump is idempotent: it recreates the schema if missing and clears
// each table before inserting the local rows.

import { DatabaseSync } from "node:sqlite"
import { mkdirSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import { DDL } from "../lib/db/schema.mjs"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..")

const PARENT_FIRST = [
  "users",
  "markets",
  "market_history",
  "market_participants",
  "market_prices",
  "positions",
  "transactions",
  "resolutions",
  "auth_challenges",
]

const MAX_STATEMENT_BYTES = 60_000

function parseArgs(argv) {
  const args = { out: join(ROOT, "data", "d1-import.sql") }
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--out") args.out = resolve(argv[++i])
  }
  return args
}

function literal(value) {
  if (value === null || value === undefined) return "NULL"
  if (typeof value === "number")
    return Number.isFinite(value) ? String(value) : "NULL"
  if (typeof value === "bigint") return String(value)
  return `'${String(value).replace(/'/g, "''")}'`
}

function main() {
  const args = parseArgs(process.argv.slice(2))
  const dbPath = resolve(
    process.env.SQLITE_PATH?.trim() || join(ROOT, "data", "clyma.db"),
  )
  const db = new DatabaseSync(dbPath)
  const chunks = []

  chunks.push("-- Clyma D1 import generated by scripts/export-d1-sql.mjs")
  chunks.push(DDL.trim())

  for (const table of [...PARENT_FIRST].reverse()) {
    chunks.push(`DELETE FROM ${table};`)
  }

  const counts = []
  for (const table of PARENT_FIRST) {
    const columns = db
      .prepare(`PRAGMA table_info(${table})`)
      .all()
      .map((column) => column.name)
    const rows = db.prepare(`SELECT * FROM ${table}`).all()
    counts.push([table, rows.length])
    if (rows.length === 0) continue

    const columnList = columns.join(", ")
    let pending = []
    let pendingBytes = 0

    const flush = () => {
      if (pending.length === 0) return
      chunks.push(
        `INSERT INTO ${table} (${columnList}) VALUES\n${pending.join(",\n")};`,
      )
      pending = []
      pendingBytes = 0
    }

    for (const row of rows) {
      const values = columns.map((column) => literal(row[column])).join(", ")
      const tuple = `(${values})`
      if (
        pending.length > 0 &&
        pendingBytes + tuple.length > MAX_STATEMENT_BYTES
      ) {
        flush()
      }
      pending.push(tuple)
      pendingBytes += tuple.length + 2
    }
    flush()
  }

  db.close()

  mkdirSync(dirname(args.out), { recursive: true })
  writeFileSync(args.out, `${chunks.join("\n")}\n`, "utf-8")

  console.log(`Wrote ${args.out}`)
  for (const [table, count] of counts) {
    console.log(`  ${table}: ${count} rows`)
  }
}

main()
